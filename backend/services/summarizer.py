import os
import json
from groq import Groq
from dotenv import load_dotenv

# Load environment variables from .env
load_dotenv()

class SummarizerService:
    @staticmethod
    async def process_summary(text: str, target_language: str, length_format: str, reading_level: str = "General Public") -> str:
        api_key = os.getenv("GROQ_API_KEY")
        if not api_key:
            return json.dumps({"error": "GROQ_API_KEY not found in backend/.env file."})

        print(f"⏳ Analyzing Article... (Target: {target_language}, Level: {reading_level})")
        client = Groq(api_key=api_key)

        # The prompt now enforces JSON structure and injects the reading level
        prompt = (
            f"You are an expert multilingual AI analyst.\n\n"
            f"Task: Analyze and summarize the provided article text.\n"
            f"1. Length: '{length_format}' (If 'Short', 2-3 sentences. If 'Key points', 4-6 bullet points).\n"
            f"2. Complexity: '{reading_level}' (Adapt the intellectual depth, vocabulary, and explanation style to match this exact reading level).\n"
            f"3. Target Language: {target_language} (Translate ALL outputs strictly into this language).\n\n"
            f"You must respond ONLY with a valid JSON object in the exact following format:\n"
            f"{{\n"
            f"  \"summary\": \"The generated summary text here\",\n"
            f"  \"sentiment\": \"Positive, Negative, or Neutral\",\n"
            f"  \"tone\": \"e.g., Objective, Sensationalized, Informative, Persuasive\",\n"
            f"  \"key_terms\": [\n"
            f"    {{\"term\": \"Term 1\", \"definition\": \"Definition in {target_language}\"}},\n"
            f"    {{\"term\": \"Term 2\", \"definition\": \"Definition in {target_language}\"}}\n"
            f"  ]\n"
            f"}}\n\n"
            f"ARTICLE TEXT:\n{text[:25000]}"
        )

        try:
            print("🚀 Sending analytical prompt to Groq (openai/gpt-oss-20b)...")
            chat_completion = client.chat.completions.create(
                messages=[
                    {
                        "role": "user",
                        "content": prompt,
                    }
                ],
                model="openai/gpt-oss-20b",
                response_format={"type": "json_object"} # Forces structured JSON output
            )
            print("✅ Success! Dashboard JSON generated.")
            
            # Return the raw JSON string generated by the AI
            return chat_completion.choices[0].message.content
        except Exception as e:
            print(f"❌ Groq API Error: {str(e)}")
            return json.dumps({"error": f"Model error: {str(e)}"})

    @staticmethod
    async def chat_with_article(article_text: str, question: str, target_language: str) -> str:
        api_key = os.getenv("GROQ_API_KEY")
        if not api_key:
            return "Error: GROQ_API_KEY not found in backend/.env file."

        client = Groq(api_key=api_key)
        
        prompt = (
            f"You are a highly analytical AI assistant.\n\n"
            f"ARTICLE TEXT:\n{article_text[:25000]}\n\n"
            f"USER QUESTION: {question}\n\n"
            f"Answer the user's question directly and concisely based ONLY on the article text above. "
            f"Respond entirely in {target_language}."
        )

        try:
            print("💬 Sending chat prompt to Groq...")
            chat_completion = client.chat.completions.create(
                messages=[{"role": "user", "content": prompt}],
                model="openai/gpt-oss-20b"
            )
            return chat_completion.choices[0].message.content
        except Exception as e:
            print(f"❌ Groq API Error: {str(e)}")
            return f"Error generating answer: {str(e)}"